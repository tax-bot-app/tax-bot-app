export type TopicSpec = { topic: string; patterns: Array<{ re: RegExp; score: number }> };

export function normalizeText(input: string): string {
  const s = String(input ?? "");
  // ざっくり正規化（軽い）
  // - 全角/半角の完全統一まではしない（コスト高い割に得が薄い）
  // - “匂い検知”なので includes/regex が通ること優先
  return (
    s
      .replace(/\r\n/g, "\n")
      .replace(/[　\t]+/g, " ")
      .replace(/\s+/g, " ")
      // 記号を間引く（完全除去はしない。単語がくっつき過ぎると逆に拾いにくい）
      .replace(/[「」『』【】［］（）\(\)\[\]{}<>＜＞]/g, " ")
      .trim()
  );
}

