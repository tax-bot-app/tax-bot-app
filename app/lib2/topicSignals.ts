export function inferTopics(message: string, opts?: { max?: number }): string[] {
  const m0 = normalizeText(message);
  if (!m0) return [];

  // 家族給与だけは “合わせ技” を優先
  const familyRe = /(奥さん|嫁|妻|夫|家内|子ども|子供|こども|息子|娘|長男|長女|親|父|母|親戚|親族)/i;
  const payRe = /(給料|給与|報酬|賃金|人件費|手当|払|支払|振込)/i;

  const forced: string[] = [];
  if (familyRe.test(m0) && payRe.test(m0)) forced.push("家族給与・家族役員");

  const max = Math.max(1, Math.min(6, opts?.max ?? 3));

  const scored = TOPIC_SPECS.map((spec) => {
    let score = 0;
    for (const p of spec.patterns) {
      if (p.re.test(m0)) score += p.score;
    }
    return { topic: spec.topic, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);

  const topics = scored.slice(0, max).map((x) => x.topic);
  return [...new Set([...forced, ...topics])];
}

export function inferTopicFromHistory(prevUserMessage: string | null, prevAssistantMessage: string | null): string | null {
  const u = prevUserMessage ? inferTopics(prevUserMessage, { max: 1 })[0] : null;
  if (u) return u;
  const a = prevAssistantMessage ? inferTopics(prevAssistantMessage, { max: 1 })[0] : null;
  if (a) return a;
  return null;
}

/** followup用：短文判定 */
export function isFollowupOnlyText(m: string): boolean {
  const s0 = (m ?? "").trim();
  if (!s0) return false;

  const s = s0.replace(/[！!。．…]+$/g, "").replace(/[ー〜～]+$/g, "").replace(/\s+/g, "").trim();
  const core = s.replace(/[!?！？…。．]+/g, "");
  if (!core) return true;
  if (core.length <= 10) return true;
  if (/^(よろしく|お願い).*(します|いたします|しますね|いたしますね)$/.test(core)) return true;
  return false;
}

export function isWeakUtterance(s: string): boolean {
  const t0 = (s ?? "").trim();
  if (!t0) return true;
  const t = t0.replace(/[！!。．…]+$/g, "").replace(/[ー〜～]+$/g, "").replace(/\s+/g, "").trim();
  if (t.length <= 10) return true;
  return /^(?:よろしゅう|よろしゅー)$/i.test(t);
}
